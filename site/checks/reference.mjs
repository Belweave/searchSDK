const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const code = (s) => `\`${String(s).replace(/\n/g, " ")}\``;
const display = (t) => t.replace(/NoInfer<Id>/g, "ProviderId").replace(/<NoInfer<Id>>/g, "").replace(/\bId\b/g, "ProviderId").replace(/OptionsFor<ProviderId, (\w+)>/g, "$1");

function table(head, rows) {
  return [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)].join("\n");
}

function page(title, description, body) {
  return `---\ntitle: ${title}\ndescription: ${JSON.stringify(description)}\n---\n\n${HEADER}\n\n${body.trim()}\n`;
}

function memberTable(iface, prose, used, owner) {
  return table(
    ["Name", "Type", "Meaning"],
    iface.members.map((m) => {
      const key = `${owner}.${m.name}`;
      used.add(key);
      if (!prose[key]) throw new Error(`reference.mjs: no description for ${key} (sdk/typescript/src/types.ts); add one`);
      return [`\`${m.name}${m.optional ? "?" : ""}\``, code(display(m.type)), prose[key]];
    }),
  );
}

