/** Members of each interface in a TypeScript file: name, optional, type, JSDoc. */
function interfaces(source) {
  const out = new Map();
  const re = /(?:export )?interface (\w+)(?:<[^>{]*>)?(?: extends ([^{]+))?\s*\{/g;
  for (const m of source.matchAll(re)) {
    let i = m.index + m[0].length;
    let depth = 1;
    let member = "";
    let doc = "";
    const members = [];
    while (i < source.length && depth > 0) {
      const ch = source[i];
      if (source.startsWith("/**", i) && depth === 1) {
        const end = source.indexOf("*/", i);
        doc = source.slice(i + 3, end).replace(/^\s*\*\s?/gm, "").replace(/\s+/g, " ").trim();
        i = end + 2;
        continue;
      }
      if (source.startsWith("//", i) && depth === 1) {
        i = source.indexOf("\n", i);
        continue;
      }
      if (ch === "{" || ch === "(" || ch === "<") depth += ch === "{" ? 1 : 0;
      if (ch === "}") depth -= 1;
      if ((ch === ";" && depth === 1) || depth === 0) {
        const mm = member.trim().match(/^(readonly\s+)?(\w+)(\?)?\s*(\(|:)([\s\S]*)$/);
        if (mm) {
          const type = mm[4] === "(" ? `(${mm[5]}`.replace(/\s+/g, " ").trim() : mm[5].replace(/\s+/g, " ").trim();
          members.push({ name: mm[2], optional: Boolean(mm[3]), type, doc });
        }
        member = "";
        doc = "";
        if (depth === 0) break;
      } else member += ch;
      i += 1;
    }
    out.set(m[1], { extends: m[2]?.trim() ?? null, members });
  }
  return out;
}

/** The SearchError class's public fields. */
function errorFields(source) {
  const body = source.slice(source.indexOf("export class SearchError"));
  return [...body.slice(0, body.indexOf("constructor")).matchAll(/^\s+(?:readonly )?(\w+)(\?)?: ([^;]+);/gm)].map((m) => ({ name: m[1], optional: Boolean(m[2]), type: m[3].trim() }));
}

const stringUnion = (source, name) => {
  const m = source.match(new RegExp(`export type ${name} =([^;]+);`));
  return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
};

/** Warning codes the SDK itself emits, read from its source. */
async function sdkWarnings() {
  const codes = new Set();
  for (const f of (await readdir(SDK_SRC)).filter((x) => x.endsWith(".ts"))) {
    const t = await readFile(path.join(SDK_SRC, f), "utf8");
    for (const m of t.matchAll(/warn\w*\.push\(\{ code: "([a-z_]+)"|\{ code: "([a-z_]+)", provider\b/g)) codes.add(m[1] ?? m[2]);
  }
  return [...codes].sort();
}

