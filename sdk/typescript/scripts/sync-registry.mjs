// Embeds registry/ into src/generated/registry.ts so the package needs no file
// access or JSON import support at runtime. `--check` fails on drift.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../../../registry/", import.meta.url);
const out = fileURLToPath(new URL("../src/generated/registry.ts", import.meta.url));
const read = (rel) => JSON.parse(readFileSync(new URL(rel, root), "utf8"));

const policy = read("policy.json");
const ids = readdirSync(new URL("providers/", root)).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).sort();
const providers = Object.fromEntries(ids.map((id) => {
  const spec = read(`providers/${id}.json`);
  if (spec.id !== id) throw new Error(`providers/${id}.json has id ${spec.id}`);
  delete spec.$schema;
  return [id, spec];
}));

function tsType(s) {
  if ("const" in s) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.anyOf) return s.anyOf.map(tsType).join(" | ");
  const types = Array.isArray(s.type) ? s.type : [s.type];
  return types.map((t) => {
    switch (t) {
      case "string": return "string";
      case "integer": case "number": return "number";
      case "boolean": return "boolean";
      case "null": return "null";
      case "array": return `Array<${s.items ? tsType(s.items) : "unknown"}>`;
      case "object": return "Record<string, unknown>";
      default: return "unknown";
    }
  }).join(" | ");
}

function optionsInterface(name, kind) {
  const lines = [`export interface ${name} {`];
  for (const id of ids) {
    const opts = providers[id][kind]?.providerOptions;
    if (!opts) continue;
    const fields = Object.entries(opts).map(([k, s]) => `    ${JSON.stringify(k)}?: ${tsType(s)};`);
    lines.push(`  ${id}?: {`, ...fields, "  };");
  }
  lines.push("}");
  return lines.join("\n");
}

const text = `// Generated by scripts/sync-registry.mjs from registry/. Do not edit.
import type { ProviderSpec } from "../types.ts";

export type ProviderId = ${ids.map((id) => JSON.stringify(id)).join(" | ")};

export const policy = ${JSON.stringify(policy, null, 2)} as const;

export const providers: Readonly<Record<ProviderId, ProviderSpec>> = ${JSON.stringify(providers, null, 2)};

${optionsInterface("SearchProviderOptions", "search")}

${optionsInterface("ContentsProviderOptions", "contents")}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(out, "utf8"); } catch {}
  if (current !== text) {
    console.error("src/generated/registry.ts is out of date. Run: npm run sync");
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
}
