"""Embeds registry/ into the package.

Copies the registry's JSON files byte for byte into src/searchsdk/_registry/
and generates src/searchsdk/_generated.py (provider ids and typed provider
options). With --check, changes nothing and exits 1 when either is out of date.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
REGISTRY = HERE.parent.parent.parent / "registry"
PACKAGE = HERE.parent / "src" / "searchsdk"
EMBEDDED = PACKAGE / "_registry"
GENERATED = PACKAGE / "_generated.py"


def wanted_files() -> dict[str, bytes]:
    """Relative path inside _registry/ -> bytes, for every file the runtime reads."""
    out = {
        "policy.json": (REGISTRY / "policy.json").read_bytes(),
        "steps.json": (REGISTRY / "steps.json").read_bytes(),
        "schema/provider.schema.json": (REGISTRY / "schema" / "provider.schema.json").read_bytes(),
    }
    for path in sorted((REGISTRY / "providers").glob("*.json")):
        out[f"providers/{path.name}"] = path.read_bytes()
    return out


def py_type(schema: dict[str, Any]) -> str:
    """A Python annotation for a provider-option schema (the registry's JSON Schema subset)."""
    if "const" in schema:
        return literal([schema["const"]])
    if "enum" in schema:
        return literal(schema["enum"])
    if "anyOf" in schema or "oneOf" in schema:
        parts = [py_type(s) for s in schema.get("anyOf", schema.get("oneOf", []))]
        return " | ".join(dict.fromkeys(parts))
    types = schema.get("type")
    names = types if isinstance(types, list) else [types]
    mapped = []
    for t in names:
        if t == "string":
            mapped.append("str")
        elif t == "integer":
            mapped.append("int")
        elif t == "number":
            mapped.append("float")
        elif t == "boolean":
            mapped.append("bool")
        elif t == "null":
            mapped.append("None")
        elif t == "array":
            mapped.append(f"list[{py_type(schema['items']) if 'items' in schema else 'Any'}]")
        elif t == "object":
            mapped.append("dict[str, Any]")
        else:
            mapped.append("Any")
    return " | ".join(dict.fromkeys(mapped))


def literal(values: list[Any]) -> str:
    """Literal[...] for str/int/bool/None values; floats cannot be literals, so they widen to float."""
    lits = [v for v in values if v is None or isinstance(v, (str, bool, int))]
    others = ["float" for v in values if isinstance(v, float)]
    parts = [f"Literal[{', '.join(repr(v) for v in lits)}]"] if lits else []
    return " | ".join(dict.fromkeys(parts + others)) or "Any"


def class_name(provider_id: str, kind: str) -> str:
    words = [w for w in provider_id.replace("_", "-").split("-") if w]
    return "".join(w[:1].upper() + w[1:] for w in words) + kind.capitalize() + "Options"


def render(specs: dict[str, dict[str, Any]]) -> str:
    ids = sorted(specs)
    lines = [
        '"""Generated by scripts/sync_registry.py from registry/. Do not edit."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any, Literal, TypedDict",
        "",
        f"ProviderId = Literal[{', '.join(repr(i) for i in ids)}]",
        '"""The providers in the embedded registry."""',
        "",
        f"PROVIDER_IDS: tuple[str, ...] = ({', '.join(repr(i) for i in ids)},)",
    ]
    for kind in ("search", "contents"):
        members: list[tuple[str, str]] = []
        for pid in ids:
            options = (specs[pid].get(kind) or {}).get("providerOptions")
            if options is None:
                continue
            name = class_name(pid, kind)
            fields = ", ".join(f"{k!r}: {py_type(s)}" for k, s in options.items())
            lines += ["", "", f"{name} = TypedDict({name!r}, {{{fields}}}, total=False)"]
            lines.append(f'"""Provider options for {specs[pid]["name"]} {kind}, checked against the spec at call time."""')
            members.append((pid, name))
        outer = f"{kind.capitalize()}ProviderOptions"
        fields = ", ".join(f"{pid!r}: {name}" for pid, name in members)
        lines += ["", "", f"{outer} = TypedDict({outer!r}, {{{fields}}}, total=False)"]
        lines.append(f'"""Provider options for {kind}, keyed by provider id."""')
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    files = wanted_files()
    specs = {}
    for rel, data in files.items():
        if rel.startswith("providers/"):
            spec = json.loads(data)
            if spec["id"] != rel[len("providers/") : -len(".json")]:
                raise SystemExit(f"{rel} has id {spec['id']}")
            specs[spec["id"]] = spec
    generated = render(specs)
    present = {p.relative_to(EMBEDDED).as_posix() for p in EMBEDDED.rglob("*") if p.is_file()} if EMBEDDED.exists() else set()
    stale = sorted(present - set(files))
    if check:
        problems = [rel for rel, data in files.items() if not (EMBEDDED / rel).is_file() or (EMBEDDED / rel).read_bytes() != data]
        problems += [f"{rel} (not in registry/)" for rel in stale]
        if not GENERATED.is_file() or GENERATED.read_text(encoding="utf-8") != generated:
            problems.append("_generated.py")
        if problems:
            print("Embedded registry is out of date: " + ", ".join(problems), file=sys.stderr)
            print("Run: python scripts/sync_registry.py", file=sys.stderr)
            return 1
        return 0
    for rel in stale:
        (EMBEDDED / rel).unlink()
    for rel, data in files.items():
        target = EMBEDDED / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    GENERATED.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
