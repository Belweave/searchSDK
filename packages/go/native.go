//go:embed native_catalog.json
var nativeCatalog []byte

// Operation describes one generated retained native binding. Retryable is an
// explicit replay declaration from the source generator, not a method heuristic.
type Operation struct {
	Provider       string            `json:"provider"`
	Name           string            `json:"name"`
	BaseURL        string            `json:"baseURL"`
	Path           string            `json:"path"`
	Method         string            `json:"method"`
	Response       string            `json:"response"`
	SourceURL      string            `json:"sourceURL"`
	Summary        string            `json:"summary"`
	Retryable      bool              `json:"retryable"`
	Headers        map[string]string `json:"headers"`
	Required       []Parameter       `json:"required"`
	BodyRequired   bool              `json:"bodyRequired"`
	Raw            bool              `json:"raw"`
	RawContentType string            `json:"rawContentType"`
	CommaQuery     []string          `json:"commaQuery"`
	StreamField    bool              `json:"streamField"`
	Stream         bool              `json:"stream"`
}
type Parameter struct {
	Location string `json:"location"`
	Name     string `json:"name"`
}
type NativeOptions struct {
	APIKey string
	// TeamAPIKey is used only for Exa's separate administration API.
	TeamAPIKey string
	// AccessMode permits explicit Tavily "keyless" Search/Extract access only.
	AccessMode string
	HTTP       HTTPOptions
	Retry      RetryPolicy
}
type NativeClient struct {
	provider, key, teamKey, accessMode string
	wire                               *wire
	retry                              RetryPolicy
	ops                                map[string]Operation
}

// NativeInput is the native escape hatch for open schemas. Maps/typed structures
// are copied during serialization; callers must not mutate inputs during a call.
// RawBody is buffered request data, not a stream. Multipart callers supply the
// exact Content-Type boundary generated by mime/multipart.
type NativeInput struct {
	Path    any
	Query   any
	Body    any
	RawBody []byte
	Headers http.Header
}
type NativeAttempt struct {
	Attempt    int     `json:"attempt"`
	DurationMS float64 `json:"durationMs"`
	Outcome    string  `json:"outcome"`
	Status     int     `json:"status,omitempty"`
	Code       Code    `json:"code,omitempty"`
}
type NativeMetadata struct {
	Provider  string          `json:"provider"`
	Operation string          `json:"operation"`
	Status    int             `json:"status"`
	RequestID string          `json:"requestId,omitempty"`
	Attempts  []NativeAttempt `json:"attempts"`
}
type RawResponse struct {
	Header http.Header
	Body   []byte
}
type NativeResponse[T any] struct {
	Data     T
	Metadata NativeMetadata
	Raw      json.RawMessage
}
type NativeResult struct {
	Data     json.RawMessage
	Bytes    []byte
	Text     string
	Raw      RawResponse
	Stream   *SSEStream
	Metadata NativeMetadata
}

func NewNativeClient(provider string, o NativeOptions) (*NativeClient, error) {
	w, e := newWire(o.HTTP)
	if e != nil {
		return nil, e
	}
	r, e := normalizeRetry(o.Retry)
	if e != nil {
		return nil, e
	}
	if o.AccessMode != "" && !(provider == "tavily" && (o.AccessMode == "keyed" || o.AccessMode == "keyless")) {
		return nil, fail(Configuration)
	}
	if !token(o.APIKey) && !(provider == "tavily" && o.AccessMode == "keyless" && o.APIKey == "") {
		return nil, fail(Configuration)
	}
	if o.TeamAPIKey != "" && (!token(o.TeamAPIKey) || provider != "exa") {
		return nil, fail(Configuration)
	}
	c := &NativeClient{provider: provider, key: o.APIKey, teamKey: o.TeamAPIKey, accessMode: o.AccessMode, wire: w, retry: r, ops: map[string]Operation{}}
	var catalog []Operation
	if json.Unmarshal(nativeCatalog, &catalog) != nil {
		return nil, fail(Configuration)
	}
	for _, op := range catalog {
		if op.Provider == provider {
			c.ops[op.Name] = op
		}
	}
	if len(c.ops) == 0 {
		return nil, fail(Configuration)
	}
	return c, nil
}
func (c *NativeClient) Operations() []Operation {
	// Decode the retained catalog afresh so callers cannot mutate internal policy.
	var catalog []Operation
	_ = json.Unmarshal(nativeCatalog, &catalog)
	out := []Operation{}
	for _, op := range catalog {
		if op.Provider == c.provider {
			out = append(out, op)
		}
	}
	return out
}
func absent(v any) bool {
	if v == nil {
		return true
	}
	r := reflect.ValueOf(v)
	switch r.Kind() {
	case reflect.Pointer, reflect.Interface, reflect.Slice, reflect.Map:
		return r.IsNil()
	}
	return false
}
func objectMap(x any) (map[string]any, error) {
	if absent(x) {
		return map[string]any{}, nil
	}
	if !validInputText(reflect.ValueOf(x), 0) {
		return nil, fail(InvalidRequest)
	}
	b, e := json.Marshal(x)
	if e != nil || !utf8.Valid(b) {
		return nil, fail(InvalidRequest)
	}
	var m map[string]any
	d := json.NewDecoder(bytes.NewReader(b))
	d.UseNumber()
	if d.Decode(&m) != nil || m == nil {
		return nil, fail(InvalidRequest)
	}
	return m, nil
}

// encoding/json replaces invalid UTF-8 in Go strings. Reject it before
// serialization so native path/query/body input cannot silently change meaning.
// The depth bound also makes cyclic input fail without unbounded recursion.
func validInputText(v reflect.Value, depth int) bool {
	if depth > 256 {
		return false
	}
	if !v.IsValid() {
		return true
	}
	switch v.Kind() {
	case reflect.String:
		return utf8.ValidString(v.String())
	case reflect.Interface, reflect.Pointer:
		return v.IsNil() || validInputText(v.Elem(), depth+1)
	case reflect.Map:
		it := v.MapRange()
		for it.Next() {
			if !validInputText(it.Key(), depth+1) || !validInputText(it.Value(), depth+1) {
				return false
			}
		}
	case reflect.Slice, reflect.Array:
		if v.Type().Elem().Kind() == reflect.Uint8 {
			return true // Raw JSON is checked after marshaling; binary is not text.
		}
		for i := 0; i < v.Len(); i++ {
			if !validInputText(v.Index(i), depth+1) {
				return false
			}
		}
	case reflect.Struct:
		for i := 0; i < v.NumField(); i++ {
			if v.Type().Field(i).PkgPath == "" && !validInputText(v.Field(i), depth+1) {
				return false
			}
		}
	}
	return true
}
func scalar(x any) (string, error) {
	switch v := x.(type) {
	case string:
		if !utf8.ValidString(v) {
			return "", fail(InvalidRequest)
		}
		return v, nil
	case bool:
		return strconv.FormatBool(v), nil
	case json.Number:
		if n, e := v.Float64(); e == nil && finite(n) {
			return string(v), nil
		}
	case float64:
		if finite(v) {
			return strconv.FormatFloat(v, 'g', -1, 64), nil
		}
	case int:
		return strconv.Itoa(v), nil
	case int64:
		return strconv.FormatInt(v, 10), nil
	}
	return "", fail(InvalidRequest)
}

var pathPlaceholder = regexp.MustCompile(`\{([a-zA-Z][a-zA-Z0-9_]*)\}`)

func nativeURL(op Operation, path, query map[string]any) (string, error) {
	base, e := endpoint(op.BaseURL)
	if e != nil {
		return "", e
	}
	if !strings.HasPrefix(op.Path, "/") || strings.HasPrefix(op.Path, "//") || strings.ContainsAny(op.Path, "?#\\ \t\r\n") {
		return "", fail(InvalidRequest)
	}
	used := map[string]bool{}
	var bad bool
	p := pathPlaceholder.ReplaceAllStringFunc(op.Path, func(s string) string {
		k := s[1 : len(s)-1]
		used[k] = true
		v, e := scalar(path[k])
		_, isBool := path[k].(bool)
		if isBool || e != nil || v == "" || v == "." || v == ".." {
			bad = true
			return ""
		}
		return url.PathEscape(v)
	})
	if bad || strings.ContainsAny(p, "{}") {
		return "", fail(InvalidRequest)
	}
	for k := range path {
		if !used[k] {
			return "", fail(InvalidRequest)
		}
	}
	// Never let dot segments or encoded separators in fixed source paths escape
	// the fixed origin/base. Encoded caller substitutions remain one path segment.
	for _, s := range strings.Split(op.Path, "/") {
		d, e := url.PathUnescape(s)
		if e != nil || d == "." || d == ".." {
			return "", fail(InvalidRequest)
		}
	}
	target := strings.TrimRight(base.String(), "/") + p
	u, e := url.Parse(target)
	if e != nil || u.Scheme != base.Scheme || u.Host != base.Host {
		return "", fail(InvalidRequest)
	}
	q := url.Values{}
	comma := map[string]bool{}
	for _, k := range op.CommaQuery {
		comma[k] = true
	}
	for k, x := range query {
		if x == nil {
			continue
		}
		if a, ok := x.([]any); ok {
			parts := []string{}
			for _, v := range a {
				s, e := scalar(v)
				if e != nil {
					return "", e
				}
				if comma[k] {
					parts = append(parts, s)
				} else {
					q.Add(k, s)
				}
			}
			if comma[k] {
				q.Add(k, strings.Join(parts, ","))
			}
			continue
		}
		if m, ok := x.(map[string]any); ok {
			for child, v := range m {
				if v == nil {
					continue
				}
				s, e := scalar(v)
				if e != nil {
					return "", e
				}
				q.Add(k+"["+child+"]", s)
			}
			continue
		}
		s, e := scalar(x)
		if e != nil {
			return "", e
		}
		q.Add(k, s)
	}
	u.RawQuery = q.Encode()
	return u.String(), nil
}
func (c *NativeClient) prepare(op Operation, in NativeInput) (string, http.Header, []byte, error) {
	path, e := objectMap(in.Path)
	if e != nil {
		return "", nil, nil, e
	}
	query, e := objectMap(in.Query)
	if e != nil {
		return "", nil, nil, e
	}
	h, e := copyHeaders(in.Headers)
	if e != nil {
		return "", nil, nil, e
	}
	authName, authValue := "", ""
	switch c.provider {
	case "context", "tavily", "perplexity", "linkup", "firecrawl":
		authName = "Authorization"
		authValue = "Bearer " + c.key
	case "brave":
		authName = "X-Subscription-Token"
		authValue = c.key
	case "exa", "tinyfish", "parallel", "you", "serper", "wondersearch":
		authName = "X-API-Key"
		authValue = c.key
	}
	supplemental := strings.HasPrefix(op.BaseURL, "https://logos.context.dev") || strings.HasPrefix(op.BaseURL, "https://x402.tavily.com")
	if supplemental {
		authName = ""
		authValue = ""
	}
	if c.provider == "tavily" && c.key == "" && !supplemental {
		if op.Name != "search" && op.Name != "extract" {
			return "", nil, nil, fail(Configuration)
		}
		authName = "X-Tavily-Access-Mode"
		authValue = "keyless"
	}
	if strings.HasPrefix(op.BaseURL, "https://admin-api.exa.ai") {
		if c.teamKey == "" {
			return "", nil, nil, fail(Configuration)
		}
		authValue = c.teamKey
	}
	// Prohibit alternate ambient/caller credentials even on public supplemental hosts.
	for k := range h {
		switch strings.ToLower(k) {
		case "authorization", "x-api-key", "x-subscription-token", "x-tavily-access-mode":
			return "", nil, nil, fail(InvalidRequest)
		}
	}
	if authName != "" {
		h.Set(authName, authValue)
	}
	for k, v := range op.Headers {
		if h.Get(k) == "" {
			h.Set(k, v)
		}
	}
	for _, p := range op.Required {
		var x any
		switch p.Location {
		case "path":
			x = path[p.Name]
		case "query":
			x = query[p.Name]
		case "header":
			x = h.Get(p.Name)
		}
		if x == nil || x == "" {
			return "", nil, nil, fail(InvalidRequest)
		}
	}
	if c.provider == "serpapi" {
		if _, ok := query["api_key"]; ok {
			return "", nil, nil, fail(InvalidRequest)
		}
		if _, ok := query["output"]; ok {
			return "", nil, nil, fail(InvalidRequest)
		}
		if query["async"] == true && query["no_cache"] == true {
			return "", nil, nil, fail(InvalidRequest)
		}
		if op.Name == "google" {
			query["engine"] = "google"
		}
		if op.Name == "extract" || op.Name == "extractMarkdown" {
			query["engine"] = "extract"
		}
		if op.Name != "locations" && op.Name != "uploadImage" {
			query["api_key"] = c.key
		}
	}
	if c.provider == "serper" && op.Method == "GET" {
		if _, ok := query["apiKey"]; ok {
			return "", nil, nil, fail(InvalidRequest)
		}
		query["apiKey"] = c.key
		h.Del("X-API-Key")
	}
	if c.provider == "context" && (op.Name == "logoUrl" || op.Name == "headLogo") {
		if s, ok := query["publicClientId"].(string); !ok || strings.TrimSpace(s) == "" {
			return "", nil, nil, fail(InvalidRequest)
		}
		if s, ok := query["domain"].(string); !ok || strings.TrimSpace(s) == "" {
			return "", nil, nil, fail(InvalidRequest)
		}
		for k, v := range query {
			if k != "publicClientId" && k != "domain" && k != "theme" && k != "type" {
				return "", nil, nil, fail(InvalidRequest)
			}
			if _, ok := v.(string); !ok {
				return "", nil, nil, fail(InvalidRequest)
			}
		}
		if s, ok := query["theme"]; ok && s != "light" && s != "dark" {
			return "", nil, nil, fail(InvalidRequest)
		}
		if s, ok := query["type"]; ok && s != "icon" && s != "wordmark" {
			return "", nil, nil, fail(InvalidRequest)
		}
	}
	bodyPresent := !absent(in.Body)
	rawPresent := in.RawBody != nil
	if bodyPresent && rawPresent || (op.Method == "GET" || op.Method == "HEAD") && (bodyPresent || rawPresent) || op.BodyRequired && !op.Raw && !bodyPresent || op.Raw && !rawPresent || !op.Raw && rawPresent {
		return "", nil, nil, fail(InvalidRequest)
	}
	var b []byte
	if bodyPresent {
		if !validInputText(reflect.ValueOf(in.Body), 0) {
			return "", nil, nil, fail(InvalidRequest)
		}
		b, e = json.Marshal(in.Body)
		if e != nil || !utf8.Valid(b) || !json.Valid(b) {
			return "", nil, nil, fail(InvalidRequest)
		}
		if op.StreamField {
			var body map[string]any
			if decodeJSON(b, &body) != nil || body == nil {
				return "", nil, nil, fail(InvalidRequest)
			}
			if v, ok := body["stream"]; ok && v != op.Stream {
				return "", nil, nil, fail(UnsupportedOption)
			}
			if c.provider == "exa" && op.Name == "searchStream" && body["outputSchema"] == nil {
				return "", nil, nil, fail(InvalidRequest)
			}
			body["stream"] = op.Stream
			b, _ = json.Marshal(body)
		}
		h.Set("Content-Type", "application/json")
	} else if rawPresent {
		b = append([]byte{}, in.RawBody...)
		if h.Get("Content-Type") == "" {
			h.Set("Content-Type", op.RawContentType)
		}
		if strings.HasPrefix(op.RawContentType, "multipart/") && h.Get("Content-Type") == op.RawContentType {
			return "", nil, nil, fail(InvalidRequest)
		}
	}
	if c.provider == "serpapi" && op.Name == "uploadImage" {
		b, e = serpMultipart(h, b, c.key)
		if e != nil {
			return "", nil, nil, e
		}
	}
	if op.Response == "sse" {
		if h.Get("Accept") != "" && h.Get("Accept") != "text/event-stream" {
			return "", nil, nil, fail(UnsupportedOption)
		}
		h.Set("Accept", "text/event-stream")
	}
	target, e := nativeURL(op, path, query)
	return target, h, b, e
}

// Call executes exactly one retained native binding, with opt-in retries only for
// generated replay-safe operations. No pagination, job polling or SSE reconnect.
func (c *NativeClient) Call(ctx context.Context, name string, in NativeInput) (NativeResult, error) {
	var out NativeResult
	op, ok := c.ops[name]
	if !ok {
		return out, fail(UnsupportedOption)
	}
	ctx, cancel := context.WithTimeout(ctx, c.wire.timeout)
	keep := false
	defer func() {
		if !keep {
			cancel()
		}
	}()
	target, h, b, e := c.prepare(op, in)
	if ctx.Err() != nil {
		return out, contextError(ctx)
	}
	if e != nil {
		return out, e
	}
	out.Metadata = NativeMetadata{Provider: c.provider, Operation: name, Attempts: []NativeAttempt{}}
	if op.Response == "embedding-url" {
		out.Text = target
		return out, nil
	}
	if e = c.wire.acquire(ctx); e != nil {
		cancel()
		return out, e
	}
	var releaseOnce sync.Once
	release := func() { releaseOnce.Do(func() { c.wire.release(); cancel() }) }
	defer func() {
		if !keep {
			release()
		}
	}()
	for i := 0; ; i++ {
		started := time.Now()
		resp, err := c.wire.send(ctx, op.Method, target, h, b)
		if err == nil {
			out.Metadata.Status = resp.StatusCode
			for _, key := range []string{"x-request-id", "request-id", "x-search-id"} {
				id := resp.Header.Get(key)
				if idPattern.MatchString(id) {
					out.Metadata.RequestID = id
					break
				}
			}
			if op.Response == "sse" {
				var stream *SSEStream
				stream, err = newSSE(ctx, resp, c.wire.limit, release)
				if err == nil {
					out.Stream = stream
					keep = true
				}
			} else {
				var raw []byte
				raw, err = readCapped(ctx, resp, c.wire.limit)
				if err == nil {
					switch op.Response {
					case "json":
						var v any
						if decodeJSON(raw, &v) != nil {
							err = fail(InvalidResponse)
						} else {
							out.Data = append(json.RawMessage{}, raw...)
						}
					case "text":
						if !utf8.Valid(raw) {
							err = fail(InvalidResponse)
						} else {
							out.Text = string(raw)
						}
					case "empty":
						if len(raw) != 0 {
							err = fail(InvalidResponse)
						}
					case "bytes":
						out.Bytes = raw
					case "raw":
						out.Raw = RawResponse{Header: resp.Header.Clone(), Body: raw}
					default:
						err = fail(Configuration)
					}
				}
			}
		}
		if ctx.Err() != nil {
			err = contextError(ctx)
		}
		a := NativeAttempt{Attempt: i + 1, DurationMS: float64(time.Since(started)) / float64(time.Millisecond), Outcome: "success", Status: out.Metadata.Status}
		if err == nil {
			out.Metadata.Attempts = append(out.Metadata.Attempts, a)
			return out, nil
		}
		se := cleanError(err)
		a.Outcome = "error"
		a.Code = se.Code
		a.Status = se.Status
		out.Metadata.Attempts = append(out.Metadata.Attempts, a)
		if !op.Retryable || !transient(se.Code) || i >= c.retry.MaxRetries {
			return NativeResult{}, se
		}
		if e = retryWait(ctx, c.retry, i, se); e != nil {
			return NativeResult{}, e
		}
	}
}
func nativeCall[T any](ctx context.Context, c *NativeClient, name string, in NativeInput) (NativeResponse[T], error) {
	ctx, cancel := context.WithTimeout(ctx, c.wire.timeout)
	keep := false
	defer func() {
		if !keep {
			cancel()
		}
	}()
	var out NativeResponse[T]
	r, e := c.Call(ctx, name, in)
	if e != nil {
		return out, e
	}
	out.Metadata = r.Metadata
	out.Raw = r.Data
	var value any
	op := c.ops[name]
	switch op.Response {
	case "json":
		if decodeJSON(r.Data, &out.Data) != nil {
			return NativeResponse[T]{}, fail(InvalidResponse)
		}
		if ctx.Err() != nil {
			return NativeResponse[T]{}, contextError(ctx)
		}
		return out, nil
	case "text", "embedding-url":
		value = r.Text
	case "empty":
		value = struct{}{}
	case "bytes":
		value = r.Bytes
	case "raw":
		value = r.Raw
	case "sse":
		value = r.Stream
	}
	// Generated named aliases retain the underlying type; reflection conversion
	// avoids unsafe or a second serialization of streams and binary data.
	from, to := reflect.ValueOf(value), reflect.ValueOf(&out.Data).Elem()
	if from.IsValid() && from.Type().ConvertibleTo(to.Type()) {
		to.Set(from.Convert(to.Type()))
		if r.Stream != nil {
			keep = true
			context.AfterFunc(r.Stream.ctx, cancel)
		}
		return out, nil
	}
	if r.Stream != nil {
		r.Stream.Close()
	}
	return NativeResponse[T]{}, fail(InvalidResponse)
}
func serpMultipart(h http.Header, b []byte, key string) ([]byte, error) {
	// Rebuild the bounded caller multipart with the factory credential. Alternate
	// credential fields are rejected; filename and content type are preserved.
	req := &http.Request{Header: h, Body: io.NopCloser(bytes.NewReader(b))}
	reader, e := req.MultipartReader()
	if e != nil {
		return nil, fail(InvalidRequest)
	}
	var out bytes.Buffer
	writer := multipart.NewWriter(&out)
	image := false
	for {
		part, e := reader.NextPart()
		if e == io.EOF {
			break
		}
		if e != nil {
			return nil, fail(InvalidRequest)
		}
		name := part.FormName()
		if name == "api_key" {
			part.Close()
			return nil, fail(InvalidRequest)
		}
		if name == "image" {
			image = true
		}
		dst, e := writer.CreatePart(part.Header)
		if e != nil {
			part.Close()
			return nil, fail(InvalidRequest)
		}
		_, e = io.Copy(dst, part)
		part.Close()
		if e != nil {
			return nil, fail(InvalidRequest)
		}
	}
	if !image {
		return nil, fail(InvalidRequest)
	}
	if writer.WriteField("api_key", key) != nil || writer.Close() != nil {
		return nil, fail(InvalidRequest)
	}
	h.Set("Content-Type", writer.FormDataContentType())
	return out.Bytes(), nil
}

// NativeProviders lists the providers with generated attributed endpoint clients.
func NativeProviders() []string {
	var ops []Operation
	_ = json.Unmarshal(nativeCatalog, &ops)
	set := map[string]bool{}
	for _, o := range ops {
		set[o.Provider] = true
	}
	out := []string{}
	for p := range set {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}
func mergeQuery(extra map[string]any, typed any) any {
	out := map[string]any{}
	for k, v := range extra {
		out[k] = v
	}
	m, e := objectMap(typed)
	if e != nil {
		return typed
	}
	for k, v := range m {
		out[k] = v
	}
	return out
}
func mergeHeaders(extra http.Header, typed any) http.Header {
	h := extra.Clone()
	if h == nil {
		h = make(http.Header)
	}
	m, e := objectMap(typed)
	if e != nil {
		h["\x00invalid"] = []string{""}
		return h
	}
	for k, v := range m {
		if v == nil {
			continue
		}
		s, e := scalar(v)
		if e != nil {
			h["\x00invalid"] = []string{""}
			return h
		}
		h.Set(k, s)
	}
	return h
}
