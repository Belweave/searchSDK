#!/usr/bin/env python3
"""Offline named C++ wrappers from retained, attributed provider operation tables."""
import argparse
import hashlib
import json
import pathlib
import re
import sys
from schema import Schemas

PACKAGE = pathlib.Path(__file__).resolve().parents[1]
ROOT = PACKAGE.parents[1]
CLASSES = {p: p[0].upper() + p[1:] for p in (
    'brave', 'context', 'exa', 'firecrawl', 'linkup', 'parallel', 'perplexity',
    'serpapi', 'serper', 'tavily', 'tinyfish', 'wondersearch', 'you')}
CLASSES.update({'serpapi': 'SerpApi', 'tinyfish': 'TinyFish', 'wondersearch': 'WonderSearch'})


def generate():
    sources = [ROOT / 'scripts/providers-a/operations.json'] + sorted(
        (ROOT / 'scripts/providers-b/catalogs').glob('*-operations.json'))
    operations = []
    digests = []
    originals = {}
    def read(path):
        data=path.read_bytes()
        relative=path.relative_to(ROOT).as_posix()
        if not any(item['path']==relative for item in digests):
            digests.append({'path':relative,'sha256':hashlib.sha256(data).hexdigest()})
        return json.loads(data)
    for directory in ('providers-a','providers-b'):
        manifest=read(ROOT/'scripts'/directory/'provenance.json')
        for entry in manifest['sources']:
            filename=entry.get('artifact',entry.get('file'))
            expected=entry.get('artifactSha256',entry.get('sha256'))
            if filename and expected:
                path=ROOT/'scripts'/directory/filename
                actual=hashlib.sha256(path.read_bytes()).hexdigest()
                if actual!=expected:
                    raise ValueError('Retained snapshot digest mismatch: '+str(path))
                digests.append({'path':path.relative_to(ROOT).as_posix(),'sha256':actual})
    for source in sources:
        data = source.read_bytes()
        relative = source.relative_to(ROOT).as_posix()
        digests.append({'path': relative, 'sha256': hashlib.sha256(data).hexdigest()})
        table = json.loads(data)
        if isinstance(table, dict):
            table = table['operations']
        for row in table:
            provider = row.get('provider', source.name.removesuffix('-operations.json'))
            originals[(provider,row['name'])]=row
            operations.append({
                'provider': provider, 'name': row['name'],
                'method': row.get('verb', row.get('method')),
                'path': row['path'], 'response': row.get('mode', row.get('response', 'json')),
                'source': row['source'], 'table': relative,
            })
    operations.sort(key=lambda row: (row['provider'], row['name']))
    if len(operations) != 493 or set(o['provider'] for o in operations) != set(CLASSES):
        raise ValueError('Expected reviewed 493 operations across 13 native providers; review scope changes explicitly')
    keys = [(o['provider'], o['name']) for o in operations]
    if len(set(keys)) != len(keys):
        raise ValueError('Duplicate operation names')
    schemas=Schemas(ROOT,read,CLASSES)
    typed=[schemas.operation(row,originals[(row['provider'],row['name'])]) for row in operations]
    typed_by_key=dict(zip(keys,typed))
    lines = [
        '// Generated by packages/cpp/scripts/generate.py. Do not edit.',
        '// Source attribution and input hashes: native-manifest.json; retained schemas in scripts/providers-{a,b}.',
        '#pragma once', '#include <searchsdk/native-types.hpp>', '#include <array>',
        'namespace searchsdk::native {',
        'namespace detail {',
        'inline Config provider_config(Config config, const char* provider) {',
        '    if (!config.gateway_url.empty() || (!config.provider.empty() && config.provider!=provider)) throw Error(Code::configuration);',
        '    config.provider=provider; return config;',
        '}', '}',
        'struct OperationInfo { std::string_view provider, name, method, path, response_mode, source; };',
        f'inline constexpr std::array<OperationInfo, {len(operations)}> operation_info{{{{',
    ]
    for row in operations:
        lines.append('    {' + ', '.join(json.dumps(row[k]) for k in ('provider', 'name', 'method', 'path', 'response', 'source')) + '},')
    lines += ['}};']
    checks = ['// Generated compile/dispatch coverage for every named wrapper.', '#pragma once', '#include <searchsdk/native.hpp>',
              'struct NamedOperation { const char* provider; const char* name; searchsdk::NativeResponse (*call)(const searchsdk::Client&, const searchsdk::NativeInput&, const searchsdk::CallOptions&); };',
              'inline const NamedOperation named_operations[] = {']
    for provider, classname in sorted(CLASSES.items()):
        lines += [f'class {classname} {{', 'public:',
                  f'    explicit {classname}(Client client) : client_(std::move(client)) {{ if (client_.provider()!="{provider}") throw Error(Code::configuration); }}',
                  f'    explicit {classname}(Config config) : {classname}(Client(detail::provider_config(std::move(config), "{provider}"))) {{}}',
                  '    Client client() const { return client_; }']
        for row in [o for o in operations if o['provider'] == provider]:
            name = row['name']
            if not re.fullmatch(r'[a-zA-Z_]\w*', name):
                raise ValueError(f'Invalid C++ identifier: {name}')
            lines += [f'    // {row["method"]} {row["path"]}; {row["response"]}. Source: {row["source"]}',
                      f'    NativeResponse {name}(const NativeInput& input={{}}, const CallOptions& options={{}}) const {{ return client_.native("{name}", input, options); }}']
            entry=typed_by_key[(provider,name)]
            if entry['response']:
                response=entry['response']
                lines.append(f'    wire::Result<{response}> {name}(const {entry["stem"]}Input& input, const CallOptions& options={{}}) const {{ return client_.native_decoded("{name}",[&]{{return input.native();}},options,[](NativeResponse raw){{return wire::result<{response}>(std::move(raw));}}); }}')
            else:
                lines.append(f'    NativeResponse {name}(const {entry["stem"]}Input& input, const CallOptions& options={{}}) const {{ return client_.native_decoded("{name}",[&]{{return input.native();}},options,[](NativeResponse raw){{return raw;}}); }}')
            if row['response']=='sse':
                lines.append(f'    NativeResponse {name}(const NativeInput& input, const std::function<bool(SseEvent)>& callback, const CallOptions& options={{}}) const {{ return client_.stream("{name}",input,callback,options); }}')
                lines.append(f'    NativeResponse {name}(const {entry["stem"]}Input& input, const std::function<bool(SseEvent)>& callback, const CallOptions& options={{}}) const {{ return client_.stream_encoded("{name}",[&]{{return input.native();}},callback,options); }}')
            checks.append(f'    {{"{provider}", "{name}", [](const searchsdk::Client& client, const searchsdk::NativeInput& input, const searchsdk::CallOptions& options) {{ return searchsdk::native::{classname}(client).{name}(input, options); }}}},')
        lines += ['private:', '    Client client_;', '};']
    lines += ['} // namespace searchsdk::native', '']
    checks += ['};', '']
    manifest = {'schemaVersion': 1, 'operationCount': len(operations), 'providerCount': len(CLASSES),
                'typedJsonResponses':schemas.typed_operations,'schemaStructCount':len(schemas.definitions),
                'inputs': sorted({item['path']:item for item in digests}.values(),key=lambda item:item['path']), 'operations': operations}
    return {
        PACKAGE / 'include/searchsdk/native.hpp': '\n'.join(lines),
        PACKAGE / 'include/searchsdk/native-types.hpp': schemas.header(typed),
        PACKAGE / 'tests/named-operations.hpp': '\n'.join(checks),
        PACKAGE / 'native-manifest.json': json.dumps(manifest, indent=2) + '\n',
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, expected in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != expected:
                stale.append(str(path.relative_to(PACKAGE)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    if stale:
        print('Stale generated C++ files: ' + ', '.join(stale), file=sys.stderr)
        return 1
    print('C++ native wrappers: 493 operations, 13 providers' + (' (verified)' if args.check else ' (generated)'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
