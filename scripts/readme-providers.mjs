// Writes the provider table in README.md from registry/providers/*.json, between
// the readme-providers markers. `--check` changes nothing and fails on drift.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const readmeUrl = new URL("README.md", root);
const dir = new URL("registry/providers/", root);
const start = "<!-- readme-providers:start (generated by scripts/readme-providers.mjs; do not edit) -->";
const end = "<!-- readme-providers:end -->";

const specs = readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .map((f) => JSON.parse(readFileSync(new URL(f, dir), "utf8")))
  .sort((a, b) => a.name.localeCompare(b.name, "en"));

function verification(spec) {
  const statuses = ["search", "contents"].filter((k) => spec[k]).map((k) => [k, spec[k].verification.status]);
  const distinct = [...new Set(statuses.map(([, s]) => s))];
  return distinct.length === 1 ? distinct[0] : statuses.map(([k, s]) => `${k}: ${s}`).join(", ");
}

const rows = specs.map((s) =>
  `| [${s.name}](https://searchsdk.dev/providers/${s.id}) | \`${s.id}\` | ${s.search ? "✓" : "—"} | ${s.contents ? "✓" : "—"} | ${verification(s)} |`);
const table = [
  start,
  "| Provider | `provider` | `search` | `contents` | Live verification |",
  "| --- | --- | :---: | :---: | --- |",
  ...rows,
  end,
].join("\n");

const readme = readFileSync(readmeUrl, "utf8");
const from = readme.indexOf(start);
const to = readme.indexOf(end);
if (from < 0 || to < from) throw new Error("README.md lacks the readme-providers markers");
const next = readme.slice(0, from) + table + readme.slice(to + end.length);

if (process.argv.includes("--check")) {
  if (next !== readme) {
    console.error("README.md provider table is out of date with registry/. Run: node scripts/readme-providers.mjs");
    process.exitCode = 1;
  }
} else if (next !== readme) writeFileSync(readmeUrl, next);
